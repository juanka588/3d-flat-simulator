/* global console, process */
// Generates docs/MATERIALS-CREDITS.md from catalog.json only (offline).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const catalogPath = resolve(root, 'apps/web/public/materials/catalog.json');
export const creditsPath = resolve(root, 'docs/MATERIALS-CREDITS.md');

const SOURCES = {
  ambientcg: { name: 'ambientCG', url: 'https://ambientcg.com', licenceUrl: 'https://docs.ambientcg.com/license/' },
  polyhaven: { name: 'Poly Haven', url: 'https://polyhaven.com', licenceUrl: 'https://polyhaven.com/license' },
};

export function renderCredits(catalog) {
  const entries = [...catalog].sort((x, y) => x.id.localeCompare(y.id));
  const lines = [
    '# Material library credits',
    '',
    '<!-- Generated by `pnpm materials:credits` from apps/web/public/materials/catalog.json. Do not edit by hand. -->',
    '',
    'All textures in the library are released under [CC0 1.0 Universal](https://creativecommons.org/publicdomain/zero/1.0/) (public domain dedication).',
    'Attribution is not required, but we credit the sources. The files shipped here are resized (1024 px; 512 px for fine woven fabrics) and re-encoded WebP derivatives of the originals.',
    '',
    ...Object.values(SOURCES).map((s) => `- ${s.name}: ${s.url} (licence: ${s.licenceUrl})`),
    '',
    '| Material | Source | Original | Licence | Retrieved |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const e of entries) {
    const src = SOURCES[e.source]?.name ?? e.source;
    lines.push(`| ${e.name} (\`${e.id}\`) | ${src} | [${e.sourceId}](${e.sourceUrl}) | ${e.license} | ${e.retrievedAt.slice(0, 10)} |`);
  }
  lines.push('');
  return lines.join('\n');
}

export function writeCredits() {
  const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));
  writeFileSync(creditsPath, renderCredits(catalog));
  return catalog.length;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`wrote ${creditsPath} (${writeCredits()} materials)`);
}
