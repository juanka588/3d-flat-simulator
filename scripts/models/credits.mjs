/* global console, process */
// Generates docs/MODELS-CREDITS.md from catalog.json (offline): pnpm models:credits
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const catalogPath = resolve(root, 'apps/web/public/models/catalog.json');
export const hdCatalogPath = resolve(root, 'apps/web/public/models-hd/catalog.json');
export const creditsPath = resolve(root, 'docs/MODELS-CREDITS.md');

/** The light-tier (`light`) or HD-tier (`hd`) catalog from disk; a missing file is an empty list. */
export function readCatalog(tier) {
  try { return JSON.parse(readFileSync(tier === 'hd' ? hdCatalogPath : catalogPath, 'utf8')); } catch { return []; }
}

const SOURCES = {
  polyhaven: { name: 'Poly Haven', url: 'https://polyhaven.com', licenceUrl: 'https://polyhaven.com/license' },
  kenney: { name: 'Kenney', url: 'https://kenney.nl', licenceUrl: 'https://creativecommons.org/publicdomain/zero/1.0/' },
  sketchfab: { name: 'Sketchfab', url: 'https://sketchfab.com', licenceUrl: 'https://creativecommons.org/licenses/by/4.0/' },
  objaverse: { name: 'Objaverse (Sketchfab authors)', url: 'https://objaverse.allenai.org', licenceUrl: 'https://creativecommons.org/licenses/by/4.0/' },
};

export function renderCredits(catalog, packs = {}, hd = readCatalog('hd')) {
  const entries = [...catalog].sort((x, y) => x.id.localeCompare(y.id));
  const hdEntries = [...hd].sort((x, y) => x.id.localeCompare(y.id));
  const used = new Set([...entries, ...hdEntries].map((e) => e.provider));
  const lines = [
    '# 3D model library credits',
    '',
    '<!-- Generated by `pnpm models:credits` from apps/web/public/models/catalog.json. Do not edit by hand. -->',
    '',
    'The models in `apps/web/public/models` and `apps/web/public/models-hd` (the lazy hero tier, listed at the end) are released under [CC0 1.0 Universal](https://creativecommons.org/publicdomain/zero/1.0/) (public domain dedication)',
    'or, when a row says `CC-BY-4.0`, under [CC BY 4.0](https://creativecommons.org/licenses/by/4.0/) (attribution required: the credit in the table must stay with the model).',
    'The shipped GLB files are normalised derivatives of the originals (re-pivoted to the item frame, welded, simplified when over 20k triangles, WebP textures, Meshopt compression).',
    '',
    ...[...used].map((p) => `- ${SOURCES[p]?.name ?? p}: ${SOURCES[p]?.url ?? ''} (licence: ${SOURCES[p]?.licenceUrl ?? ''})`),
    ...Object.entries(packs).map(([id, p]) => `- Pack \`${id}\`: ${p.name} by ${p.author}, ${p.homepage}`),
    '',
    '| Model | Provider | Original | Author | Licence | Retrieved |',
    '| --- | --- | --- | --- | --- | --- |',
  ];
  for (const e of entries) {
    lines.push(`| ${e.name} (\`${e.id}\`) | ${SOURCES[e.provider]?.name ?? e.provider} | [${e.sourceId.split('/').pop()}](${e.sourceUrl}) | ${e.author ?? ''} | ${e.licence} | ${e.retrievedAt.slice(0, 10)} |`);
  }
  if (hdEntries.length) {
    lines.push(
      '',
      '## HD models (`apps/web/public/models-hd`, lazy tier)',
      '',
      'Hero models fetched only when an item that resolves to one is placed. Every CC BY 4.0 row must keep its credit (title, author, source, licence); the app shows the same lines in the Library tab, under "Model credits".',
      '',
      '| Model | Original title and author | Source | Licence | Retrieved |',
      '| --- | --- | --- | --- | --- |',
    );
    for (const e of hdEntries) {
      lines.push(`| ${e.name} (\`${e.id}\`) | ${String(e.credit ?? '').replace(/\|/g, '/')} | [${SOURCES[e.provider]?.name ?? e.provider}](${e.sourceUrl}) | ${e.licence} | ${e.retrievedAt.slice(0, 10)} |`);
    }
  }
  lines.push('');
  return lines.join('\n');
}

export function writeCredits() {
  const catalog = JSON.parse(readFileSync(catalogPath, 'utf8'));
  let packs = {};
  try { packs = JSON.parse(readFileSync(resolve(dirname(fileURLToPath(import.meta.url)), 'manifest.json'), 'utf8')).packs ?? {}; } catch { /* no manifest */ }
  writeFileSync(creditsPath, renderCredits(catalog, packs));
  return catalog.length + readCatalog('hd').length;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(`wrote ${creditsPath} (${writeCredits()} models)`);
}
